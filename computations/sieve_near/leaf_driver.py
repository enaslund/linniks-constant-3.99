def goutleaf(inp, anchors, model='outside', families=False):
    """Outside-buffer leaf with graded rows.  families=False omits every family; 'second' adds the
    reserved height-one second family (anchor <= lambda1^lo); 'outside_first' additionally puts the
    outside first family into the family row at s1 (sieve part zero)."""
    import certificate_out as CO
    s1 = safe_anchor(inp)
    plist = [graded_parameters(inp, s) if (families and Q(s) == s1) else propose_params.params(s1, Q(s))
             for s in anchors]
    rows = []
    for s, p in zip(anchors, plist):
        fm = families
        if families == 'outside_first' and Q(s) != s1:
            fm = 'second' if inp.get('second') else False
        rows.append(graded_row(inp, p, families=fm))
    return CO.OutLeaf(inp, rows, model=model), plist


def gblockleaf(inp, anchors, hidden=None):
    """Hidden-family branch leaf (first zero inside) with the family row and graded rows,
    first and reserved second families included.  hidden=True (default for 'distinct' branches)
    gives the hidden global family features in the family row; elsewhere hidden columns are omitted."""
    import certificate_out as CO
    if hidden is None:
        hidden = inp.get('identity') == 'distinct' and os.environ.get('SIEVE_BLOCK_HIDDEN', '1') == '1'
    s1 = safe_anchor(inp)
    plist = [graded_parameters(inp, s) for s in anchors]
    return CO.OutLeaf(inp, [graded_row(inp, p, families=True, hidden=(hidden and Q(p['s']) == s1)) for p in plist],
                      model='block'), plist



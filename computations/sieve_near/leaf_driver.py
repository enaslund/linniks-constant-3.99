def gadaptive_certify_out(inp, max_anchors=4, float_margin=0.99, max_boxes=20000, log=print, init_anchors=None):
    import certificate_out as CO
    anchors = sorted(set(Q(a) for a in (init_anchors or [])))

    def worst_fn(A, starts=2, grid=12):
        ol, _ = goutleaf(inp, A)
        return float_worst_out(ol, starts=starts, grid=grid)[0]
    val = worst_fn(anchors, 3, 14)
    log(('gfloat', [str(a) for a in anchors], round(val, 6)))

    def greedy(anchors, val, cap, margin):
        while val >= margin and len(anchors) < cap:
            best = None
            for c in gmenu_for(inp, anchors):
                v = worst_fn(sorted(anchors+[c]))
                if best is None or v < best[0]:
                    best = (v, c)
            if best is None or best[0] >= val-1e-4:
                break
            anchors = sorted(anchors+[best[1]]); val = best[0]
            log(('ggreedy', [str(a) for a in anchors], round(val, 6)))
        return anchors, val
    anchors, val = greedy(anchors, val, max_anchors, float_margin)
    tries = 0
    while True:
        ol, plist = goutleaf(inp, anchors)
        try:
            tree, mx, nb = CO.build(ol, max_boxes=max_boxes)
            return dict(rows=[dict(kind='graded_out', parameters=p) for p in plist], tree=tree, maximum=mx,
                        boxes=nb, anchors=[str(a) for a in anchors])
        except CannotCertify as e:
            log(('cert-fail', [str(a) for a in anchors], e.args[0], e.value))
            tries += 1
            if tries > 2:
                raise
            anchors2, _ = greedy(anchors, 2.0, len(anchors)+1, 0.0)
            if anchors2 == anchors:
                raise
            anchors = anchors2


def verify_out(inp, record, model='outside'):
    import certificate_out as CO
    if 'rows' in record:
        sieve = []
        for rs in record['rows']:
            if model == 'outside':
                assert rs['kind'] in ('graded_out', 'graded_out_sec', 'graded_out_first')
                if rs['kind'] == 'graded_out_first':
                    s1 = safe_anchor(inp)
                    fm = 'outside_first' if Q(rs['parameters']['s']) == s1 else ('second' if inp.get('second') else False)
                else:
                    fm = 'second' if rs['kind'] == 'graded_out_sec' else False
                sieve.append(graded_row(inp, rs['parameters'], families=fm))
            else:
                assert rs['kind'] in ('graded_block', 'graded_block_fam', 'graded_block_famh')
                hid = rs['kind'] == 'graded_block_famh' and Q(rs['parameters']['s']) == safe_anchor(inp)
                sieve.append(graded_row(inp, rs['parameters'], families=(rs['kind'] != 'graded_block'), hidden=hid))
    else:
        assert model == 'outside'
        sieve = [sieve_rows(inp, sieve_test(p)) for p in record['sieve_parameters']]
    ol = CO.OutLeaf(inp, sieve, model=model)
    mx, nb = CO.verify_tree(ol, record['tree'])
    assert mx == record['maximum']
    return mx, nb


# ------------------------------------------------------------ fast staged driver for full covers
def staged_certify(inp, outside=False, log=print, margins=(0.97, 0.98, 0.99), max_rows=6, max_boxes=20000,
                   stages=None, mu_range=None, model='outside'):
    """Try small graded row sets first, then greedy additions; returns a record.

    Inside leaves always carry the family row (anchor s1).  Stage sets are
    reference anchors added to it; outside leaves use graded rows only."""
    s1 = safe_anchor(inp)
    if stages is None:
        stages = [[Q(19, 10)], [Q(19, 10), Q(23, 10)], [Q(3, 2), Q(19, 10), Q(23, 10)]]
    import os
    base = [] if (outside and model == 'outside' and not inp.get('second')
                  and os.environ.get('SIEVE_OUT_FIRST') != '1') else [s1]

    osec = outside and model == 'outside' and bool(inp.get('second'))
    ofirst = outside and model == 'outside' and os.environ.get('SIEVE_OUT_FIRST') == '1'

    def build(A):
        if outside and model == 'block':
            return gblockleaf(inp, A)
        if outside:
            fm = 'outside_first' if ofirst else ('second' if osec else False)
            return goutleaf(inp, A, model=model, families=fm)
        return gleafdata(inp, A, mu_range=mu_range)

    def worst(A, starts=2, grid=12):
        obj, _ = build(A)
        return (float_worst_out if outside else float_worst)(obj, starts=starts, grid=grid)[0]

    def certify_set(A):
        obj, plist = build(A)
        if outside:
            import certificate_out as CO
            tree, mx, nb = CO.build(obj, max_boxes=max_boxes)
            kind = ('graded_out_sec' if osec else 'graded_out') if model == 'outside' else 'graded_block_fam'
            if model == 'block' and any('vh' in sv for sv in obj.sieve):
                kind = 'graded_block_famh'
            if model == 'outside' and ofirst:
                kind = 'graded_out_first'
        else:
            tree, mx, nb = C2.build(obj, max_boxes=max_boxes)
            kind = 'graded'
        rec = dict(rows=[dict(kind=kind, parameters=p) for p in plist], tree=tree, maximum=mx, boxes=nb,
                   anchors=[str(a) for a in A])
        if mu_range is not None:
            rec['mu_range'] = [str(mu_range[0]), None if mu_range[1] is None else str(mu_range[1])]
        return rec
    tried = []
    A = None
    for k, st in enumerate(stages):
        A = sorted(set(base+[a for a in st if a > s1]))
        v = worst(A)
        log(('stage', [str(a) for a in A], round(v, 6)))
        if v < margins[min(k, len(margins)-1)]:
            try:
                return certify_set(A)
            except CannotCertify as e:
                log(('cert-fail', [str(a) for a in A], e.args[0], e.value))
                tried.append(A)
    # greedy additions from the last stage
    val = worst(A)
    if len(A) >= max_rows and val >= margins[-1]:
        raise CannotCertify('floating maximum above margin at the row limit', None, val)
    for _ in range(3):
        while len(A) < max_rows and (val >= margins[-1] or A in tried):
            best = None
            for c in gmenu_for(inp, A):
                if c <= s1:
                    continue
                vv = worst(sorted(A+[c]))
                if best is None or vv < best[0]:
                    best = (vv, c)
            if best is None:
                break
            A = sorted(A+[best[1]]); val = best[0]
            log(('ggreedy', [str(a) for a in A], round(val, 6)))
            if val < margins[-1] and A not in tried:
                break
        try:
            return certify_set(A)
        except CannotCertify as e:
            log(('cert-fail', [str(a) for a in A], e.args[0], e.value))
            tried.append(A)
            if len(A) >= max_rows:
                raise
    raise CannotCertify('staged driver exhausted')


RC_MU_SPLIT = (('0', '1'), ('1', None))


def rc_split_certify(inp, log=print, **kw):
    """rc inside leaves: certify each range of the first zero's normalized height separately."""
    parts = []
    for mr in RC_MU_SPLIT:
        log(('mu_range', mr))
        parts.append(staged_certify(inp, log=log, mu_range=mr, **kw))
    return dict(mu_split=parts, maximum=max(p['maximum'] for p in parts), boxes=sum(p['boxes'] for p in parts),
                anchors=[p['anchors'] for p in parts])


# ------------------------------------------------------------ case splits of hard leaves
def regen_split(inp, L, path):
    """Regenerate a sub-case of a captured leaf: the repository's split_specs applied along
    `path` = [(axis, mid, side), ...], then the same far/collective choices and the refined
    real/real third bound.  The children of a split exhaust the parent case."""
    from refinement_cover import split_specs
    sp = spec_of(inp)
    for axis, mid, side in path:
        kids = split_specs(sp, axis, mid)
        sp = kids[side]
    out = make_endgame(sp, L, parse_params(inp), inp['lambda_den'])
    if out is None:
        return None
    if 'far_parameters' in inp:
        out = replace_far(out, inp['far_parameters'])
    if 'collective_envelope' in inp:
        out = apply_collective(out, [r['parameters'] for r in inp['collective_envelope']['cohorts']])
    import third_refine
    return third_refine.refine_third(out)


def second_split_points(inp, k):
    """k-1 interior points splitting the reserved second-family interval into k equal parts."""
    lo, hi = Q(inp['ordinary_lower']), Q(inp['second']['hi'])
    return [lo+(hi-lo)*i/k for i in range(1, k)]


def split_certify(inp4, L, mids, axis='second', log=print, **kw):
    """Certify every sub-case of a split along `axis` at the given interior points."""
    children = []
    for i in range(len(mids)+1):
        path = []
        # child i: right of mids[i-1] (side 1) then left of mids[i] (side 0)
        if i > 0:
            path.append((axis, str(mids[i-1]), 1))
        if i < len(mids):
            path.append((axis, str(mids[i]), 0))
        inp = regen_split(inp4, L, path)
        if inp is None:
            children.append(dict(path=path, excluded_by_location=True)); continue
        log(('split-child', i, [str(m) for m in mids]))
        rec = rc_split_certify(inp, log=log, **kw) if inp['case']['kind'] == 'rc' else staged_certify(inp, log=log, **kw)
        rec['path'] = path
        children.append(rec)
    return dict(split=dict(axis=axis, mids=[str(m) for m in mids]), children=children,
                maximum=max(c.get('maximum', -1) for c in children), boxes=sum(c.get('boxes', 0) for c in children))


def verify_split(inp4, L, record):
    """Verify a split record against the captured parent leaf."""
    mids = [Q(m) for m in record['split']['mids']]
    axis = record['split']['axis']
    assert all(a < b for a, b in zip(mids, mids[1:]))
    assert len(record['children']) == len(mids)+1
    mx = -1; nb = 0
    for i, ch in enumerate(record['children']):
        path = []
        if i > 0:
            path.append((axis, str(mids[i-1]), 1))
        if i < len(mids):
            path.append((axis, str(mids[i]), 0))
        assert [tuple(p) for p in ch['path']] == path
        inp = regen_split(inp4, L, path)
        if ch.get('excluded_by_location'):
            assert inp is None
            continue
        m, n = verify(inp, ch)
        mx = max(mx, m); nb += n
    assert mx == record['maximum']
    return mx, nb


